/** 全部手写剖析，按母题 id 排在一起；语义模板那部分覆盖它的每一张皮肤。 */
export const WORD_PROBLEM_EXPLAINS = [...CRAFTED_EXPLAINS, ...SEMANTIC_EXPLAINS, ...SKIN_EXPLAINS]

/** 手写条数。内容自检与 Round 17/18 门禁（H4 ≥ 20、H5 ≥ 80）读这个值。 */
export const EXPLAIN_COUNT = WORD_PROBLEM_EXPLAINS.length

const SKIN_IDS = new Set(SCENE_SKINS.map((skin) => skin.id))
/** `sum-gap-bamboo` 这种已经指名到皮肤的 id 不必再展开，展开只会造出对不上任何母题的键。 */
const isSkinned = (id) => SKIN_IDS.has(id.slice(id.lastIndexOf('-') + 1))

/**
 * id → 剖析。
 * 先把写明的 id 落位，再把 `语义-皮肤` 的组合补上——两趟走是为了保证
 * 万一某张皮肤的组合名撞上了另一条手写母题的 id，赢的一定是那条手写母题；
 * 皮肤专写的那条也是靠这个顺序赢过它所属的语义模板。
 */
const EXPLAIN_MAP = new Map()
for (const explain of WORD_PROBLEM_EXPLAINS) EXPLAIN_MAP.set(explain.id, explain)
for (const explain of WORD_PROBLEM_EXPLAINS) {
  if (isSkinned(explain.id)) continue
  for (const skin of SCENE_SKINS) {
    const id = `${explain.id}-${skin.id}`
    if (!EXPLAIN_MAP.has(id)) EXPLAIN_MAP.set(id, explain)
  }
}

/** 查一道题有没有手写剖析；没有就返回 null，由 wpAnalysis 退回公式兜底。 */
export function explainOf(questionId) {
  return EXPLAIN_MAP.get(String(questionId ?? '')) ?? null
}

/** 手写剖析实际覆盖到的母题 id（含皮肤展开），内容自检用它对账。 */
export function explainedIds() {
  return [...EXPLAIN_MAP.keys()]
}

/** 数讲解句时用的示例数值：分步是函数，不跑一遍就只能数出函数体，数不出句子。 */
const SAMPLE_STEP = { a: 12, b: 3, value: 4, quotient: 4, remainder: 0, op: '÷' }
const SAMPLE_QUESTION = { unit: '个' }

/**
 * 去重后的讲解句：整题思路 + 图示读法 + 每一步（拿同一组示例数值渲染）。
 *
 * 同一组数值渲染是故意的——两条剖析只有措辞不同才会各留一句，
 * 复制粘贴改个 id 的会自己合并掉，数出来的就是真写过的句子数。
 */
export function explainSentences() {
  const out = new Set()
  for (const explain of WORD_PROBLEM_EXPLAINS) {
    if (explain.headline) out.add(explain.headline)
    if (explain.caption) out.add(explain.caption)
    for (const [index, write] of (explain.steps ?? []).entries()) {
      if (typeof write !== 'function') continue
      let line = ''
      try {
        line = String(
          write({ ...SAMPLE_STEP, index, all: [], question: SAMPLE_QUESTION }) ?? '',
        ).trim()
      } catch {
        continue
      }
      if (line) out.add(line)
    }
  }
  return [...out]
}

/** 去重中文讲解句数。Round 18 门禁（H5 ≥ 200）读这个值。 */
export const EXPLAIN_SENTENCE_COUNT = explainSentences().length
