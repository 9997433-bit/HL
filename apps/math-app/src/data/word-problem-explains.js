/**
 * 应用题手写剖析链（ROUND17_H4）。
 *
 * 剖析壳（ROUND16_H5）的分步是解析 equation 得来的，好处是每加一个母题都自动有
 * 剖析，坏处是它只会说「两部分要合成一个总数，用加法」这种放之四海皆准的话——
 * 孩子卡住的地方从来不是「加法是什么」，而是「为什么这一步先算它」。
 *
 * 这份表补的就是那句话：按母题 id 逐条手写「老师会怎么讲这一步」，
 * 拿到手写就用手写，没写过的母题仍旧走公式兜底，一步都不会少。
 *
 * 一条剖析写三件事：
 *   headline 整道题的思路（顶掉母题自带的 hint，讲的是「为什么这么列式」）
 *   caption  图示那条线该怎么读（顶掉按运算符套的通用说明）
 *   steps    分步文案，一个函数写一步，顺序与 analyzeEquation 拆出的步骤一一对应
 *
 * 分步函数收到的是那一步的实况，不必自己解析算式：
 *   a / b        这一步的两个操作数（有余数除法里是被除数与除数）
 *   value        这一步的得数
 *   quotient / remainder  有余数除法的商与余数
 *   op           这一步的运算符
 *   index / all  第几步、全部步骤
 *   question     整道题（用得最多的是 question.unit）
 *
 * 两条硬约束：
 *   1. **判题前不许写出答案。** 被问的那一步（step.asked）在界面上是盖住的，
 *      文案里就不能出现它的得数——所以最后一步只讲 a、b 和该怎么想，不报结果。
 *      wpAnalysis 里还有一道运行时兜底：真写漏了就退回公式文案，绝不泄题。
 *   2. **语义模板的文案不许出现具体名词。** `join-shell` 与 `join-bakery` 共用
 *      同一条剖析（见下面的 id 展开规则），说「贝壳」就会串到面包坊去；
 *      要提量词只能用 question.unit。手写母题的题面是固定的，可以放开写。
 *
 * id 怎么对上：手写母题直接用它的 id；语义模板用语义 id（如 `join`），
 * 查表时自动展开成 `join-shell`、`join-bakery`……一条覆盖它的全部皮肤。
 */
