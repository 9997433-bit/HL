/** 这个字的形近字，没有就返回空数组。 */
export function similarChars(char) {
  const packed = SIMILAR_MAP.get(char)
  return packed ? [...packed] : []
}

/** 两个字算不算形近（任一方向命中都算）。 */
export function isSimilar(a, b) {
  return (SIMILAR_MAP.get(a)?.includes(b) ?? false) || (SIMILAR_MAP.get(b)?.includes(a) ?? false)
}
