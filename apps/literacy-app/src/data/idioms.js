export function getIdiom(id) {
  return IDIOM_MAP.get(id) || null
}

/** 成语中出现的全部汉字（去重），供离线笔顺数据生成脚本使用。 */
export function idiomChars() {
  const set = new Set()
  for (const idiom of IDIOMS) {
    for (const ch of idiom.word) set.add(ch)
  }
  return [...set]
}

