/** 兜底：新加单元还没配剧情时，用单元自己的副标题顶上，不留空白。 */
const fallback = (unit) => `${unit.desc}，这一站的字都在这儿等你。`

/** 已解锁单元的一句话剧情。 */
export const unitStory = (unit) => (unit ? (STORIES[unit.id] ?? fallback(unit)) : '')

/** 还没解锁时的一句话预告：先说门为什么关着，再把里面的风景漏一点出来。 */
export const unitTeaser = (unit) =>
  unit ? `学完上一站的 60%，「${unit.name}」的门就会打开——${unitStory(unit)}` : ''

/** 刚解锁那一下的过场台词，只播一次。 */
export const unitCheer = (unit) => (unit ? `「${unit.name}」的门开了！${unitStory(unit)}` : '')

