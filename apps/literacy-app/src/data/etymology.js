/**
 * 字源语料 —— 「这个字当初是怎么来的」。
 *
 * 每个字给两样东西，动画就是把它们串起来：
 *   1. 起点。要么是一张小图（`sketch`，形状 DSL 见 utils/etymologySketch.js），
 *      要么是几个零件（`parts`，比如「明 = 日 + 月」）；
 *   2. 终点。今天写的这个字——终点不在语料里，运行时直接取 hanzi-writer 的
 *      笔顺数据（makemeahanzi 一脉），一笔一笔写出来。
 *
 * 关于 `sketch` 要说清楚一件事：它是**我们照着字源的意思画的示意图**，
 * 不是甲骨文、金文的摹本。真甲骨拓片对五到八岁的孩子既看不清也讲不明白，
 * 而且各家写法差异很大，冒充「这就是甲骨文」是不老实的。所以界面上这一帧
 * 统一写「古人看到的样子」，把它当插画介绍，不当文物介绍。
 *
 * 字源解释按传统「六书」里的四类归口：
 *   xiang 象形 —— 照着东西画（日、月、山）
 *   zhi   指事 —— 在图上加个记号指出位置（上、下、本）
 *   hui   会意 —— 两个部件的意思合起来（明、休、看）
 *   xing  形声 —— 一半表意思，一半表读音（河、花、妈）
 *
 * 这里收的每个字都必须在字表里（`npm run check:data` 会核对），
 * 这样「写一写」那一帧一定有离线笔顺数据，断网也能演完整个动画。
 *
 * 本文件只放**手写**的那一批——有小图的象形 / 指事字，和故事各不相同的会意字。
 * 形声字的讲法高度同构（形旁管意思 + 声旁管读音），一个一个抄没有意义，
 * 它们由 scripts/gen-etymology.mjs 从 scripts/data/etymology-seed.txt 派生，
 * 落在 etymology-derived.js，在文件末尾并进同一份 ETYMOLOGY。
 */

